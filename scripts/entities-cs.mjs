// Writes the .NET copy of the HTML named-reference table (D24) from src/server/entities.ts, so
// both servers decode the same names. Run after changing entities.ts; EntityTableTests.cs fails
// while the two differ.   node scripts/entities-cs.mjs
import { writeFileSync } from 'node:fs';
import { LEGACY, PACKED } from '../src/server/entities.ts';

const out = 'dotnet/src/Umage.Redline.AspNetCore/Editing/Entities.g.cs';
const chunks = PACKED.match(/[^;]+(?:;|$)/g).reduce((lines, e) => {
  if (lines.length && lines[lines.length - 1].length + e.length <= 110) lines[lines.length - 1] += e;
  else lines.push(e);
  return lines;
}, []);

writeFileSync(out, `// <auto-generated> by scripts/entities-cs.mjs from src/server/entities.ts. Don't edit. </auto-generated>
// The HTML named character references (WHATWG list), packed as "name,hex[.hex];…" (D24).

namespace Umage.Redline.Editing;

internal static class Entities
{
    public const string Packed =
${chunks.map(c => `        "${c}"`).join(' +\n')};

    /// <summary>Names browsers also decode without the trailing semicolon (legacy, in text content).</summary>
    public const string Legacy = "${LEGACY}";
}
`);
console.log(`wrote ${out}`);
